// Small self-hosted flight frames. Original OSM SVG/data remain downloadable.
import sharp from 'sharp';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
const locations=JSON.parse(await readFile('src/data/project-locations.json','utf8'));
const output='public/maps/flight'; await mkdir(output,{recursive:true});
const {data,info}=await sharp('public/visuals/v2/earth-day.webp').removeAlpha().raw().toBuffer({resolveWithObject:true});
const size=640,rad=Math.PI/180;
for(const [id,point] of Object.entries(locations)){
 const pixels=Buffer.alloc(size*size*4),lat=point.lat*rad,lon=point.lng*rad;
 for(let y=0;y<size;y++)for(let x=0;x<size;x++){
  const u=(x+.5-size/2)/(size*.47),v=-(y+.5-size/2)/(size*.47),r=u*u+v*v;
  if(r>1)continue;
  const z=Math.sqrt(1-r),latitude=Math.asin(v*Math.cos(lat)+z*Math.sin(lat));
  const longitude=lon+Math.atan2(u,z*Math.cos(lat)-v*Math.sin(lat));
  const tx=Math.floor(((longitude/(2*Math.PI)+.5)%1+1)%1*info.width),ty=Math.min(info.height-1,Math.floor((.5-latitude/Math.PI)*info.height));
  const from=(ty*info.width+tx)*3,to=(y*size+x)*4,light=.48+.52*Math.sqrt(z);
  for(let c=0;c<3;c++)pixels[to+c]=Math.round(data[from+c]*light);
  pixels[to+3]=Math.round(Math.min(1,(1-r)*size/2)*255);
 }
 await sharp(pixels,{raw:{width:size,height:size,channels:4}}).webp({quality:86}).toFile(`${output}/${id}-planet.webp`);
 for(const stage of ['region','city','location'])for(const width of [640,1280]){
  const source=stage==='location'?`public/maps/${id}.svg`:`public/maps/context/${id}-${stage}.svg`;
  await sharp(source).resize(width,Math.round(width*9/16),{fit:'cover'}).webp({quality:width===640?75:88}).toFile(`${output}/${id}-${stage}-${width}.webp`);
 }
}
await writeFile(`${output}/README.txt`,'Flight previews derived from project OSM extracts (ODbL-1.0) and NASA/GSFC Earth imagery. Exact owner-supplied GPS centers. Original data: ../ and ../context/. Generated by scripts/build-flight-previews.mjs.');
console.log('Built compact flight frames for',Object.keys(locations).length,'parks');
